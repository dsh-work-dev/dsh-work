// Shared renderer, built with the repository's locked frontend toolchain.
import {build} from '../frontend/node_modules/esbuild/lib/main.js';
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const result=await build({entryPoints:[fileURLToPath(new URL('../browser-extension/src/actionIndicatorRenderer.ts',import.meta.url))],bundle:true,format:'esm',platform:'browser',write:false,loader:{'.png':'dataurl','.svg':'text'}});
const {install}=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].contents).toString('base64'));
const output=new URL('../native/embeddedbrowser/action_indicator_asset.h',import.meta.url);
const chunks=Array.from({length:Math.ceil(install.length/2048)},(_,i)=>'R"DSH_INDICATOR('+install.slice(i*2048,(i+1)*2048)+')DSH_INDICATOR"');
const content='// Generated by scripts/build-action-indicator.mjs; shared with the extension.\nconst std::string kActionIndicatorInstall = std::string('+chunks[0]+')'+chunks.slice(1).map(chunk=>' +\n'+chunk).join('')+';\n';
let previous;try{previous=readFileSync(output,'utf8')}catch{}
if(previous!==content)writeFileSync(output,content);
