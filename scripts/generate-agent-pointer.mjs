import fs from 'node:fs';

// Shared by the browser indicator and future desktop-overlay consumers.
const directory = new URL('../frontend/public/branding/', import.meta.url);
const source = new URL('agent-pointer.json', directory);
const destination = new URL('agent-pointer.svg', directory);
const pointer = JSON.parse(fs.readFileSync(source, 'utf8'));
const {width, height, path, glow, fill, outline, outlineWidth} = pointer;

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" overflow="visible">
  <defs>
    <filter id="glow" x="-120%" y="-120%" width="340%" height="340%">
      <feGaussianBlur stdDeviation="${glow.blur}"/>
    </filter>
    <filter id="glow-core" x="-120%" y="-120%" width="340%" height="340%">
      <feGaussianBlur stdDeviation="${glow.core.blur}"/>
    </filter>
    <clipPath id="body"><path d="${path}"/></clipPath>
  </defs>
  <g class="halo">
    <path d="${path}" fill="none" stroke="${glow.color}" stroke-width="${glow.width}" opacity="${glow.opacity}" filter="url(#glow)"/>
    <path d="${path}" fill="none" stroke="${glow.color}" stroke-width="${glow.core.width}" opacity="${glow.core.opacity}" filter="url(#glow-core)"/>
  </g>
  <path d="${path}" fill="${fill}" stroke="${outline}" stroke-width="${outlineWidth}" stroke-linejoin="miter" clip-path="url(#body)"/>
</svg>`;
const output = '<!-- Generated by scripts/generate-agent-pointer.mjs from agent-pointer.json. -->\n' + svg + '\n';

// Avoid triggering a dev rebuild when the shared source has not changed.
if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) {
  fs.writeFileSync(destination, output);
}
