let activeLocale: Locale = defaultLocale;
const listeners = new Set<LocaleListener>();

export function normalizeLocale(value: unknown): Locale {
  return value === "en" || value === "zh-CN" || value === "ja-JP" ? value : defaultLocale;
}

export function currentLocale(): Locale {
  return activeLocale;
}

export function t(key: string, params: MessageParams = {}): string {
  return renderMessage(key, activeLocale, params);
}

// renderMessage resolves one message template without touching the active
// locale. translateDocument uses it to compare copy across every locale.
function renderMessage(key: string, locale: Locale, params: MessageParams): string {
  const template = messages[locale][key] ?? messages[defaultLocale][key] ?? key;
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}

const locales: Locale[] = ["en", "zh-CN", "ja-JP"];

export function hasTranslationInEveryLocale(key: string): boolean {
	return locales.every((locale) => typeof messages[locale][key] === "string" && messages[locale][key].length > 0);
}

// isStaticCopy reports whether element text is still translatable copy for a
// data-i18n key: the original markup text or one of that key's translations.
// A value written by render code is never copy and must not be overwritten.
export function isStaticCopy(current: string, key: string, original: string): boolean {
  if (current === original) {
    return true;
  }
  return locales.some((locale) => renderMessage(key, locale, {}) === current);
}

// originalCopy records the markup text of each data-i18n element on the first
// translation pass, before any render code has written a value into it.
const originalCopy = new WeakMap<HTMLElement, string>();

function translateDocument() {
  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (!key) {
      return;
    }
    if (!originalCopy.has(element)) {
      originalCopy.set(element, element.textContent ?? "");
    }
    if (!isStaticCopy(element.textContent ?? "", key, originalCopy.get(element) ?? "")) {
      return;
    }
    element.textContent = t(key);
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (key) {
      element.setAttribute("aria-label", t(key));
    }
  });
  document.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (key) {
      element.placeholder = t(key);
    }
  });
}

export function applyLocale(value: unknown): Locale {
  const locale = normalizeLocale(value);
  const changed = activeLocale !== locale;
  activeLocale = locale;
  document.documentElement.lang = locale;
  translateDocument();
  if (changed) {
    listeners.forEach((listener) => {
      listener(locale);
    });
  }
  return locale;
}

export function subscribeLocale(listener: LocaleListener): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function mountLocale() {
  Events.On("locale", (event) => applyLocale(event.data));
}
